// Builds engine/words.js from SCOWL (npm package wordlist-english, MIT).
//   node bakeoff/engine/build-words.mjs
// common = SCOWL size 10-20 (everyday words, used for picking puzzle words); all = sizes 10-50 (used to accept guesses).
// Only lowercase a-z words of 3-7 letters, so no proper nouns, abbreviations or apostrophes.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const load = (sizes) => sizes.flatMap((n) => ["english", "american"].flatMap((v) => require(`wordlist-english/${v}-words-${n}.json`)));
const clean = (ws) => [...new Set(ws.filter((w) => /^[a-z]{3,7}$/.test(w)))].sort();

const common = clean(load([10, 20]));
const all = clean(load([10, 20, 35, 40, 50])).filter((w) => !common.includes(w));
fs.writeFileSync(path.join(here, "words.js"),
  "// Generated by build-words.mjs from SCOWL (wordlist-english, MIT). Do not edit by hand.\n" +
  `export const WORDS = {\n  common: ${JSON.stringify(common.join(" "))},\n  all: ${JSON.stringify(all.join(" "))},\n};\n`);
console.log(`common ${common.length} words, all ${common.length + all.length} words`);
